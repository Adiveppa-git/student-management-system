"""FastAPI Router for AI-Powered Academic Risk Prediction and Model Inspection.

Provides secure, leak-free, validated endpoints for:
1. POST /api/ai/benchmark-predict - Single-student inference with strict UCI schema and disclaimers.
2. GET /api/ai/model-metrics - Inspection of actual saved test evaluation metrics and limitations.
3. GET /api/ai/health - Model readiness and artifact integrity verification.
"""

from typing import Any, Dict
from fastapi import APIRouter, File, HTTPException, Response, UploadFile, status

from app.models.ai_schemas import (
    BenchmarkPredictionResponse,
    ModelHealthResponse,
    ModelMetricsResponse,
    UCIBenchmarkStudentInput,
)
from app.models.college_schemas import CollegeDatasetAuditResponse
from app.ml.college_data_prep import MAX_CSV_FILE_SIZE_BYTES, parse_and_audit_college_csv
from app.ml.predictor import (
    check_model_health,
    get_metadata,
    get_metrics,
    predict_student_risk,
)

router = APIRouter(prefix="/api/ai", tags=["AI Academic Risk & Early Warning"])

BENCHMARK_DISCLAIMER = (
    "EXPERIMENTAL BENCHMARK MODEL: This prediction is generated by a model trained exclusively "
    "on secondary-school mathematics data from Portugal (Cortez & Silva, 2008). It is NOT intended, "
    "calibrated, or validated for making academic determinations for college students or Indian engineering "
    "degree programs. Do not make high-stakes interventions based solely on this prediction."
)

DOMAIN_APPLICABILITY_NOTE = (
    "Domain Applicability Notice: Reliable academic prediction for Indian engineering colleges requires "
    "local institution metrics (continuous internals, assignment scores, university attendance percentages, "
    "VTU backlogs, and semester SGPA/CGPA). This benchmark model does not accept or process those college-specific indicators."
)

EVALUATION_LIMITATIONS = [
    (
        "The benchmark dataset represents secondary school students (ages 15-22) in Portugal and does NOT "
        "establish predictive performance on Indian engineering college students."
    ),
    (
        "Features require Portuguese secondary school variables (parental cohabitation, jobs, alcohol consumption, "
        "absence counts, and 0-20 scale term-1 grades), which differ fundamentally from Indian university credit "
        "systems (USN, branches, CIE, SEE, SGPA/CGPA, and backlogs)."
    ),
    (
        "Predictions reflect holdout test evaluation on 79 samples; real-world deployment requires localized "
        "institutional data collection and validation."
    ),
]


@router.post(
    "/benchmark-predict",
    response_model=BenchmarkPredictionResponse,
    status_code=status.HTTP_200_OK,
    summary="Generate academic risk prediction using UCI benchmark model",
    description=(
        "Accepts the 31 validated features expected by the trained UCI benchmark model. "
        "Returns risk prediction, probability, risk tier, and mandatory experimental disclaimers."
    ),
)
def benchmark_predict(student: UCIBenchmarkStudentInput) -> Dict[str, Any]:
    """Execute prediction on the pre-loaded Scikit-learn pipeline."""
    try:
        features_dict = student.model_dump()
        prediction = predict_student_risk(features_dict)
        metadata = get_metadata()
    except FileNotFoundError:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Academic risk model artifact is unavailable. Please ensure model training has been completed.",
        )
    except Exception:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while evaluating the academic risk model.",
        )

    model_name = metadata.get("experiment", {}).get("best_model", "Random Forest Classifier")
    source_url = metadata.get("source_url", "https://archive.ics.uci.edu/dataset/320/student+performance")

    return {
        "is_at_risk": prediction["is_at_risk"],
        "risk_status": prediction["risk_status"],
        "risk_probability": prediction["risk_probability"],
        "confidence": prediction["confidence"],
        "risk_level": prediction["risk_level"],
        "model_name": model_name,
        "dataset_source": source_url,
        "disclaimer": BENCHMARK_DISCLAIMER,
        "domain_applicability_note": DOMAIN_APPLICABILITY_NOTE,
        "evaluated_features_count": prediction["evaluated_features_count"],
    }


@router.get(
    "/model-metrics",
    response_model=ModelMetricsResponse,
    status_code=status.HTTP_200_OK,
    summary="Retrieve actual saved evaluation metrics and audit details",
    description=(
        "Returns the test-set evaluation metrics (accuracy, precision, recall, F1, confusion matrix) "
        "of the persisted model, along with model comparison and domain limitations."
    ),
)
def get_model_metrics() -> Dict[str, Any]:
    """Retrieve saved evaluation metrics and feature metadata."""
    try:
        metadata = get_metadata()
        metrics = get_metrics()
    except FileNotFoundError:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Model metrics or metadata artifacts are unavailable.",
        )
    except Exception:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to load model evaluation metrics.",
        )

    best_model = metrics.get("model_selection", {}).get("recommended_model", "Random Forest")
    rf_metrics = metrics.get("models", {}).get("random_forest", {}).get("metrics", {})
    lr_metrics = metrics.get("models", {}).get("logistic_regression", {}).get("metrics", {})

    return {
        "model_name": best_model,
        "dataset_source": metadata.get("source_url", ""),
        "citation": metadata.get("citation", ""),
        "license": metadata.get("license", ""),
        "target_definition": metadata.get("target_definition", ""),
        "passing_threshold": metadata.get("passing_threshold", 10),
        "grade_scale": metadata.get("grade_scale", "0 to 20"),
        "test_metrics": rf_metrics if best_model == "Random Forest" else lr_metrics,
        "comparison_metrics": lr_metrics if best_model == "Random Forest" else rf_metrics,
        "evaluation_limitations": EVALUATION_LIMITATIONS,
    }


@router.get(
    "/health",
    response_model=ModelHealthResponse,
    summary="Check operational readiness of the AI model pipeline",
    description="Reports whether model artifacts are intact and preloaded in memory.",
)
def model_health(response: Response) -> Dict[str, Any]:
    """Check whether model artifacts load successfully."""
    health = check_model_health()
    if health["status"] != "healthy":
        response.status_code = status.HTTP_503_SERVICE_UNAVAILABLE
    return health


@router.post(
    "/college/audit-dataset",
    response_model=CollegeDatasetAuditResponse,
    status_code=status.HTTP_200_OK,
    summary="Securely audit an authorized de-identified college CSV dataset",
    description=(
        "Uploads a CSV file of de-identified engineering college academic observations. "
        "Validates 10-point GPA scale, explicit CIE marks, attendance thresholds, detects duplicates, "
        "flags target leakage, reports class balance, and evaluates ML training readiness. "
        "Zero records are inserted into MongoDB; college model training remains blocked."
    ),
)
async def audit_college_dataset(file: UploadFile = File(...)) -> Dict[str, Any]:
    """Execute secure in-memory audit of uploaded college academic observation CSV."""
    filename = file.filename or "dataset.csv"
    if not filename.lower().endswith(".csv"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only .csv files are supported for college dataset import.",
        )

    # Read up to size limit (5 MB + 1 KB buffer)
    try:
        content = await file.read(MAX_CSV_FILE_SIZE_BYTES + 1024)
    except Exception:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Error reading uploaded file content.",
        )

    if len(content) > MAX_CSV_FILE_SIZE_BYTES:
        max_mb = MAX_CSV_FILE_SIZE_BYTES // (1024 * 1024)
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail=f"File size exceeds maximum allowable limit of {max_mb} MB.",
        )

    try:
        report = parse_and_audit_college_csv(content, filename=filename)
        return report
    except ValueError as ve:
        err_msg = str(ve)
        if "missing required column" in err_msg.lower():
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=err_msg,
            )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=err_msg,
        )
    except Exception:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while auditing the college dataset.",
        )

